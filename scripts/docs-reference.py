#!/usr/bin/env python3
"""Generate the documentation pages that mirror code.

Writes:
  docs/reference/make-targets.md   from the Makefile ``help`` recipe
  docs/reference/vpnd-commands.md  from the vpnd argparse tree
  docs/llms.txt                    from ``vpnd ai-docs``

``--check`` compares the generated text with the committed files and exits 1
when any of them drifted, without writing. No credentials, inventory or
secrets are read; the Makefile is parsed as text and the vpnd parser is built
without running a command.
"""

import argparse
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "vpnd" / "src"))

STATUS = "> **Status:** Current · **Type:** reference · **Tier:** —"
GENERATED = "<!-- Generated by `make docs-reference`. Edit the source, not this file. -->"
TARGETS = {
    "docs/reference/make-targets.md": "make_targets",
    "docs/reference/vpnd-commands.md": "vpnd_commands",
    "docs/llms.txt": "llms_txt",
}


def make_targets() -> str:
    text = (ROOT / "Makefile").read_text(encoding="utf-8")
    # GNU Make ignores blank lines inside a recipe, so the help list continues
    # past them until the next non-indented line.
    match = re.search(r"^help:\n((?:\t.*\n|\n)+)", text, re.MULTILINE)
    if not match:
        raise SystemExit("Makefile: help recipe not found")
    lines = []
    for raw in match.group(1).splitlines():
        body = raw.strip()
        if not body.startswith("@echo"):
            continue
        body = body[len("@echo") :].strip()
        if len(body) >= 2 and body[0] == body[-1] == '"':
            body = body[1:-1]
        lines.append(re.sub(r"\$\((\w+)\)", r"$\1", body).rstrip())
    return (
        "# Make targets\n\n"
        f"{STATUS}\n\n{GENERATED}\n\n"
        "The Makefile is the canonical operator surface and `make help` prints this\n"
        "list. Targets that use cloud credentials, inventory, SSH or decrypted\n"
        "secrets need user authorization first; `AGENTS.md` lists them under\n"
        "decision boundaries. A variable shown as `$NAME` takes its value from the\n"
        "environment or from the git-ignored `.fleet.mk`.\n\n"
        "```text\n" + "\n".join(lines) + "\n```\n"
    )


def vpnd_commands() -> str:
    from vpnd import cli

    parser = cli.build_parser()
    rows = [
        "# vpnd commands",
        "",
        STATUS,
        "",
        GENERATED,
        "",
        "`vpnd` is a convenience CLI in front of Make, Terraform, Ansible and SOPS;",
        "it never replaces them. The parser in `vpnd/src/vpnd/cli.py` is the single",
        "definition of flags and subcommands; the man pages and this page derive",
        "from it. Installation and development notes: [`vpnd/README.md`](../../vpnd/README.md).",
        "",
        "## Global options",
        "",
        "Every command and subcommand accepts these as well.",
        "",
        "| Option | Purpose |",
        "|---|---|",
    ]
    global_dests = set()
    for action in parser._actions:
        if action.option_strings and action.help != argparse.SUPPRESS:
            rows.append(f"| `{', '.join(action.option_strings)}` | {_help(action.help)} |")
            global_dests.add(action.dest)
    subparsers = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    rows += ["", "## Commands", "", "| Command | Purpose |", "|---|---|"]
    for name in subparsers.choices:
        rows.append(f"| `vpnd {name}` | {cli.COMMANDS[name]} |")
    for name, child in subparsers.choices.items():
        rows += ["", f"### `vpnd {name}`", "", cli.COMMANDS[name]]
        rows += _arguments(child, global_dests)
        nested = [a for a in child._actions if isinstance(a, argparse._SubParsersAction)]
        for action_name, grandchild in (nested[0].choices.items() if nested else ()):
            rows += ["", f"#### `vpnd {name} {action_name}`", "", _help(grandchild.description)]
            rows += _arguments(grandchild, global_dests)
    return "\n".join(rows) + "\n"


def _arguments(parser, global_dests) -> list:
    """Table of a parser's own positional arguments and options, without the
    global options repeated on every subcommand or the subcommand list."""
    rows = []
    for action in parser._actions:
        if isinstance(action, (argparse._SubParsersAction, argparse._HelpAction)):
            continue
        if action.dest in global_dests or action.help == argparse.SUPPRESS:
            continue
        if action.option_strings:
            label = ", ".join(action.option_strings)
            required = "yes" if action.required else "no"
        else:
            label = f"<{action.dest}>"
            required = "no" if action.nargs in ("?", "*") else "yes"
        if action.choices and not isinstance(action.choices, dict):
            label += " " + "\\|".join(str(c) for c in action.choices)
        rows.append(f"| `{label}` | {required} | {_help(action.help)} |")
    if rows:
        rows = ["", "| Argument | Required | Purpose |", "|---|---|---|", *rows]
    for group in parser._mutually_exclusive_groups:
        names = ", ".join(f"`{a.option_strings[0]}`" for a in group._group_actions)
        rows += ["", f"{'Exactly' if group.required else 'At most'} one of {names}."]
    return rows


def _help(text) -> str:
    return (text or "").replace("%(default)s", "the configured default").replace("|", "\\|").strip()


def llms_txt() -> str:
    from vpnd.commands.ai_docs import emit_docs

    with tempfile.TemporaryDirectory() as out:
        emit_docs(ROOT / "docs", out)
        return (Path(out) / "llms.txt").read_text(encoding="utf-8")


def main(argv=None) -> int:
    options = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    options.add_argument("--check", action="store_true", help="compare instead of writing; exit 1 on drift")
    args = options.parse_args(argv)
    drift = []
    for relative, producer in TARGETS.items():
        generated = globals()[producer]()
        path = ROOT / relative
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if args.check:
            if current != generated:
                drift.append(relative)
        elif current != generated:
            path.write_text(generated, encoding="utf-8")
            print(f"wrote {relative}")
    if drift:
        print("generated documentation is stale; run `make docs-reference`:\n  " + "\n  ".join(drift), file=sys.stderr)
        return 1
    if args.check:
        print(f"generated documentation is current ({len(TARGETS)} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
