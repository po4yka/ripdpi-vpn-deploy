"""Bind an OpenTofu workspace's initialization data to its backend settings."""

import hashlib
import json
import re
import sys
from pathlib import Path


# The ops backend files contain HCL literal assignments. The restore client
# rejects expressions, so it cannot resolve an object differently from OpenTofu.
TOKEN = re.compile(r'\s+|\#[^\n]*|//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|[\w.-]+|[][{},=:]|.', re.DOTALL)


def backend_literals(raw: bytes) -> dict:
    tokens = iter(t for t in TOKEN.findall(raw.decode())
                  if not t.isspace() and not t.startswith(("#", "//", "/*")))
    current = next(tokens, None)

    def take():
        nonlocal current
        value, current = current, next(tokens, None)
        if value is None:
            raise ValueError
        return value

    def literal():
        token = take()
        if token == "{":
            return attributes("}")
        if token == "[":
            values = []
            while current != "]":
                values.append(literal())
                if current != "]" and take() != ",":
                    raise ValueError
            take()
            return values
        value = json.loads(token)
        if isinstance(value, str) and any(pattern in value for pattern in ("${", "%{")):
            raise ValueError
        return value

    def attributes(end):
        result = {}
        while current != end:
            name = take()
            if end and name.startswith('"'):
                name = json.loads(name)
            if (not re.fullmatch(r"[a-zA-Z_][\w-]*", name) or name in result
                    or take() not in (("=", ":") if end else ("=",))):
                raise ValueError
            result[name] = literal()
            if end and current == ",":
                take()
        if end:
            take()
        return result

    try:
        return attributes(None)
    except (ValueError, RecursionError):
        raise ValueError("backend file must contain unique literal HCL assignments") from None


CREDENTIAL_FIELDS = {"access_key", "secret_key", "token", "session_token", "web_identity_token"}


def _contains_credentials(value) -> bool:
    if isinstance(value, dict):
        return bool(CREDENTIAL_FIELDS.intersection(value)) or any(_contains_credentials(item) for item in value.values())
    return isinstance(value, list) and any(_contains_credentials(item) for item in value)


def s3_settings(raw: bytes, provider: str | None) -> dict:
    try:
        settings = backend_literals(raw)
    except ValueError:
        # Keep a clear refusal even when an unquoted credential makes the HCL invalid.
        if re.search(rb"(?m)^\s*(access_key|secret_key|token|session_token|web_identity_token)\s*=", raw):
            raise ValueError("credential in backend file") from None
        raise ValueError("backend requires use_lockfile = true in literal HCL settings") from None
    if _contains_credentials(settings):
        raise ValueError("credential in backend file")
    if settings.get("use_lockfile") is not True:
        raise ValueError("backend requires use_lockfile = true")
    if settings.get("workspace_key_prefix") != "state/workspaces":
        raise ValueError('backend requires workspace_key_prefix = "state/workspaces"')
    # The disposable lock probe supplies its own run-specific key at init.
    if provider is not None:
        if provider not in {"upcloud", "hetzner", "vultr", "scaleway"}:
            raise ValueError("unknown provider backend file")
        if settings.get("key") != f"state/{provider}/terraform.tfstate":
            raise ValueError(f'backend requires key = "state/{provider}/terraform.tfstate"')
    return settings


def _directory(provider_root: Path, workspace: str, settings: bytes) -> Path:
    return provider_root / ".terraform-env" / workspace / hashlib.sha256(settings).hexdigest()


def read_backend_settings(root: Path, workspace: str, file: Path) -> bytes:
    if not file.is_absolute():
        raise ValueError("backend configuration needs an absolute path")
    settings = file.read_bytes()
    override = root / "ci_backend_override.tf"
    if override.exists() or override.is_symlink():
        expected = (f"# Generated by scripts/ci-real-deploy.py for {workspace}\n"
                    'terraform {\n  backend "local" {}\n}\n')
        local_settings = "workspace_dir = " + json.dumps(str(file.parent.parent / "tfstate")) + "\n"
        if (root.name != "upcloud" or not re.fullmatch(r"ci-staging-[a-f0-9]{16}", workspace)
                or override.is_symlink() or override.read_text() != expected or settings != local_settings.encode()):
            raise ValueError("CI local backend does not belong to this workspace")
    else:
        s3_settings(settings, root.name)
    return settings


def data_directory(provider_root: Path, workspace: str, backend_file: Path) -> Path:
    return _directory(provider_root, workspace, read_backend_settings(provider_root, workspace, backend_file))


def plan_scope(provider_root: Path, workspace: str, data_dir: Path) -> str:
    return f"{provider_root.name}/{workspace}/{data_dir.name}"


def main() -> None:
    if len(sys.argv) == 3 and sys.argv[1] == "--check-probe-backend":
        s3_settings(Path(sys.argv[2]).read_bytes(), None)
        return
    provider, workspace, config, snapshot = sys.argv[1:]
    root = Path(provider)
    settings = read_backend_settings(root, workspace, Path(config))
    if snapshot:
        # Pass OpenTofu the exact bytes used to choose its data directory.
        Path(snapshot).write_bytes(settings)
    print(_directory(root, workspace, settings))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        sys.exit(str(error))
