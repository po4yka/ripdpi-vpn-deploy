def _records(config: Path) -> dict[str, tuple[bytes, int, int]]:
    paths = [config / "sshd_config", *(config / "sshd_config.d").iterdir()]
    return {
        str(path.relative_to(config)): (
            path.read_bytes(),
            path.stat().st_mode,
            path.stat().st_ino,
        )
        for path in paths
    }


def _rollback_records(config: Path) -> dict[str, tuple[bytes, int, int, int]]:
    paths = [config / "sshd_config", *(config / "sshd_config.d").iterdir()]
    return {
        str(path.relative_to(config)): (
            path.read_bytes(),
            path.stat().st_mode,
            path.stat().st_uid,
            path.stat().st_gid,
        )
        for path in paths
    }


def test_fresh_bootstrap_publishes_exact_single_owner_fragments_and_is_idempotent(
    bootstrap_owner, ssh_config: Path,
) -> None:
    cloud = ssh_config / "sshd_config.d" / CLOUD
    cloud.write_bytes(b"# generated by cloud-init\n\nPasswordAuthentication no\n# retained\n")
    cloud.chmod(0o640)
    main_before = (ssh_config / "sshd_config").read_bytes()

    assert bootstrap_owner.normalize(ssh_config, "2222") is True
    fragments = ssh_config / "sshd_config.d"
    assert (fragments / BOOT).read_bytes() == (
        b"Port 2222\n"
        b"PasswordAuthentication no\n"
        b"KbdInteractiveAuthentication no\n"
        b"PermitRootLogin no\n"
        b"PubkeyAuthentication yes\n"
    )
    assert (fragments / MANAGED).read_bytes() == (
        b"# first-boot runtime owner\nX11Forwarding no\n"
    )
    assert cloud.read_bytes() == b"# generated by cloud-init\n\n# retained\n"
    assert (cloud.stat().st_mode & 0o777) == 0o640
    assert (ssh_config / "sshd_config").read_bytes() == main_before

    after = _records(ssh_config)
    assert bootstrap_owner.normalize(ssh_config, "2222") is False
    assert _records(ssh_config) == after


