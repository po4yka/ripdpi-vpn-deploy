def _write_sshd_stub(
    directory: Path,
    *,
    output: bytes | None = None,
    exit_code: int = 0,
    delay: float = 0,
    argument_log: Path | None = None,
) -> Path:
    stub = directory / f"sshd-stub-{len(tuple(directory.glob('sshd-stub-*')))}"
    if output is None:
        output_command = """config=''
while [ "$#" -gt 0 ]; do
  if [ "$1" = '-f' ]; then config=$2; shift 2; else shift; fi
done
port=$(awk '$1 == "Port" { print $2 }' "${config%/*}/sshd_config.d/10-cloud-init-hardening.conf")
printf 'port %s\\npasswordauthentication no\\nkbdinteractiveauthentication no\\npermitrootlogin no\\npubkeyauthentication yes\\nx11forwarding no\\n' "$port"
"""
    else:
        output_command = "printf %s " + shlex.quote(output.decode("ascii")) + "\n"
    log_command = ""
    if argument_log is not None:
        log_command = "printf '%s\\n' \"$@\" > " + shlex.quote(str(argument_log)) + "\n"
    stub.write_text(
        "#!/bin/sh\n"
        + log_command
        + (f"sleep {delay}\n" if delay else "")
        + output_command
        + f"exit {exit_code}\n",
        encoding="ascii",
    )
    stub.chmod(0o755)
    return stub


