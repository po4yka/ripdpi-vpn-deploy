def test_bootstrap_marker_depends_on_validated_successful_ssh_reload(
    tmp_path: Path,
) -> None:
    rendered = subprocess.run(
        [sys.executable, str(RENDERER)],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    rendered_config = yaml.safe_load(rendered)
    assert rendered_config["users"][1]["name"] == "deploy"
    hardening = next(
        item
        for item in rendered_config["write_files"]
        if item["path"] == "/usr/local/libexec/vpn-bootstrap-sshd-ownership.py"
    )
    assert base64.b64decode(hardening["content"]) == BOOTSTRAP_OWNER.read_bytes()
    assert "${" not in rendered

    cloud_config = yaml.safe_load(TEMPLATE.read_text(encoding="utf-8"))
    commands = cloud_config["runcmd"]

    assert len(commands) == 1
    assert commands[0][:2] == ["sh", "-c"]
    command = commands[0][2]
    assert "/usr/bin/python3 -I -B /usr/local/libexec/vpn-bootstrap-sshd-ownership.py" in command
    assert command.index("install -d -m 0755 /run/sshd") < command.index(
        "vpn-bootstrap-sshd-ownership.py"
    )
    assert command.index("vpn-bootstrap-sshd-ownership.py") < command.index("sshd -t")
    assert command.index("install -d -m 0755 /run/sshd") < command.index("sshd -t")
    assert command.index("sshd -t") < command.index("systemctl reload ssh")
    assert command.index("systemctl reload ssh") < command.index(f"touch {MARKER}")

    sshd = tmp_path / "sshd"
    sshd.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
    sshd.chmod(0o755)
    systemctl = tmp_path / "systemctl"
    systemctl.write_text('#!/bin/sh\nexit "${SYSTEMCTL_RC:?}"\n', encoding="utf-8")
    systemctl.chmod(0o755)
    owner = tmp_path / "bootstrap-owner"
    owner.write_text('#!/bin/sh\nexit "${OWNER_RC:?}"\n', encoding="utf-8")
    owner.chmod(0o755)
    marker = tmp_path / "bootstrap.done"
    executable = (
        command.replace("install -d -m 0755 /run/sshd && ", "")
        .replace(
            "/usr/bin/python3 -I -B /usr/local/libexec/vpn-bootstrap-sshd-ownership.py "
            "--config-dir /etc/ssh --ssh-port ${ssh_port}",
            str(owner),
        )
        .replace("/usr/sbin/sshd", str(sshd))
        .replace("systemctl", str(systemctl))
        .replace(MARKER, str(marker))
    )

    owner_failed = subprocess.run(
        ["sh", "-c", executable],
        env={**os.environ, "OWNER_RC": "1", "SYSTEMCTL_RC": "0"},
        check=False,
    )
    assert owner_failed.returncode != 0
    assert not marker.exists()

    failed = subprocess.run(
        ["sh", "-c", executable],
        env={**os.environ, "OWNER_RC": "0", "SYSTEMCTL_RC": "1"},
        check=False,
    )
    assert failed.returncode != 0
    assert not marker.exists()

    succeeded = subprocess.run(
        ["sh", "-c", executable],
        env={**os.environ, "OWNER_RC": "0", "SYSTEMCTL_RC": "0"},
        check=False,
    )
    assert succeeded.returncode == 0
    assert marker.exists()

    already_completed = subprocess.run(
        ["sh", "-c", executable],
        env={**os.environ, "OWNER_RC": "1", "SYSTEMCTL_RC": "1"},
        check=False,
    )
    assert already_completed.returncode == 0
    assert marker.exists()
