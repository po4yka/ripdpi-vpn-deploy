def test_publish_failure_rolls_back_every_fragment(
    bootstrap_owner, ssh_config: Path, monkeypatch: pytest.MonkeyPatch,
) -> None:
    fragments = ssh_config / "sshd_config.d"
    (fragments / CLOUD).write_bytes(b"# cloud\nPasswordAuthentication no\n")
    (fragments / CLOUD).chmod(0o644)
    before = _records(ssh_config)
    real_replace = bootstrap_owner.os.replace
    calls = 0

    def fail_second_publish(source, destination, *args, **kwargs):
        nonlocal calls
        calls += 1
        if calls == 2:
            raise OSError("injected publish failure")
        return real_replace(source, destination, *args, **kwargs)

    monkeypatch.setattr(bootstrap_owner.os, "replace", fail_second_publish)
    with pytest.raises(bootstrap_owner.BootstrapOwnershipError, match="publish-failed"):
        bootstrap_owner.normalize(ssh_config, "22")

    assert _records(ssh_config) == before
    assert not tuple(fragments.glob(".bootstrap-sshd-*"))


