def test_effective_runner_never_polls_or_reaps_before_terminating_owned_group(
    bootstrap_owner, ssh_config: Path, monkeypatch: pytest.MonkeyPatch,
) -> None:
    events: list[str] = []
    real_popen = bootstrap_owner.subprocess.Popen
    real_killpg = bootstrap_owner.os.killpg

    class ObservedProcess:
        def __init__(self, process):
            self._process = process
            self.stdout = process.stdout
            self.pid = process.pid

        def poll(self):
            events.append("poll")
            return self._process.poll()

        def wait(self, *args, **kwargs):
            events.append("wait")
            return self._process.wait(*args, **kwargs)

    def observed_popen(*args, **kwargs):
        return ObservedProcess(real_popen(*args, **kwargs))

    def observed_killpg(*args, **kwargs):
        events.append("killpg")
        return real_killpg(*args, **kwargs)

    monkeypatch.setattr(bootstrap_owner.subprocess, "Popen", observed_popen)
    monkeypatch.setattr(bootstrap_owner.os, "killpg", observed_killpg)

    assert bootstrap_owner.normalize(ssh_config, "22") is True

    assert events[0] == "killpg"
    assert "poll" not in events
    assert events[-1] == "wait"


def test_effective_runner_accepts_eperm_only_after_natural_zero_exit(
    bootstrap_owner, monkeypatch: pytest.MonkeyPatch,
) -> None:
    class NaturalExit:
        pid = 123456
        wait_calls = 0

        def wait(self, *, timeout):
            assert timeout == 1
            self.wait_calls += 1
            return 0

    process = NaturalExit()

    def refuse_group_signal(_pid, _signal):
        raise PermissionError(errno.EPERM, "fixture eperm")

    monkeypatch.setattr(bootstrap_owner.os, "killpg", refuse_group_signal)

    assert (
        bootstrap_owner._terminate_and_wait(
            process, allow_natural_exit_eperm=True
        )
        == 0
    )
    assert process.wait_calls == 1


