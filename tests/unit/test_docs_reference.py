"""Generated documentation stays equal to its sources.

docs/reference/make-targets.md mirrors the Makefile help recipe,
docs/reference/vpnd-commands.md mirrors the vpnd argparse tree and
docs/llms.txt mirrors the documentation tree. ``make docs-reference``
regenerates them; this test fails when a source changed without it.
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def test_generated_reference_pages_are_current() -> None:
    result = subprocess.run(
        [sys.executable, str(ROOT / "scripts/docs-reference.py"), "--check"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr


def test_generated_pages_declare_their_origin() -> None:
    for relative in ("docs/reference/make-targets.md", "docs/reference/vpnd-commands.md"):
        text = (ROOT / relative).read_text()
        assert "Generated by `make docs-reference`" in text, relative
        assert text.startswith("# "), relative


def test_global_options_name_the_subcommands_that_reject_them() -> None:
    """``vpnd host add`` replaces the global ``--env``/``--provider`` with its own
    long-only required options, so the global table must say so instead of
    promising ``-e``/``-p`` on every subcommand."""
    text = (ROOT / "docs/reference/vpnd-commands.md").read_text()
    for option in ("--env, -e", "--provider, -p"):
        row = next(line for line in text.splitlines() if line.startswith(f"| `{option}` |"))
        assert "Not accepted by `vpnd host add`" in row, row
